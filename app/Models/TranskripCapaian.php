<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

/**
 * TranskripCapaian Model
 *
 * Menyimpan snapshot capaian hafalan siswa pada waktu tertentu untuk history non-retroaktif.
 * Snapshot dibuat otomatis ketika parameter sistem berubah (target kelulusan, batas tingkat)
 * atau manual oleh Admin.
 *
 * REFACTOR 2026-08-11: Hapus tahun_ajaran_id → Transkrip dicatat berdasarkan tanggal saja
 *
 * @property int $id
 * @property int $siswa_id
 * @property \Illuminate\Support\Carbon $tanggal_generate Date when snapshot was created
 * @property string $reason Reason: 'target_kelulusan_change'|'batas_tingkat_change'|'manual_admin'|'lulus_tahfidz'|'lulus_akademik'
 * @property int|null $generated_by Admin ID who generated the snapshot (null for automated)
 * @property int $total_juz_tuntas_snapshot Count of completed juz at snapshot time
 * @property array $detail_capaian_snapshot Full progress data structure at snapshot time
 * @property int $target_kelulusan_at_snapshot System target_kelulusan value at snapshot time
 * @property array $batas_tingkat_at_snapshot System batas_tingkat configuration at snapshot time
 * @property \Illuminate\Support\Carbon|null $created_at
 * @property \Illuminate\Support\Carbon|null $updated_at
 *
 * @property-read Siswa $siswa
 * @property-read Admin|null $generatedBy
 */
class TranskripCapaian extends Model
{
    use HasFactory;

    protected $table = 'transkrip_capaians';

    protected $fillable = [
        'siswa_id',
        'tanggal_generate',
        'reason',
        'generated_by',
        'total_juz_tuntas_snapshot',
        'detail_capaian_snapshot',
        'target_kelulusan_at_snapshot',
        'batas_tingkat_at_snapshot',
    ];

    protected function casts(): array
    {
        return [
            'tanggal_generate' => 'date',
            'total_juz_tuntas_snapshot' => 'integer',
            'detail_capaian_snapshot' => 'array',
            'target_kelulusan_at_snapshot' => 'integer',
            'batas_tingkat_at_snapshot' => 'array',
        ];
    }

    /**
     * Relationship: TranskripCapaian belongs to a Siswa
     */
    public function siswa()
    {
        return $this->belongsTo(Siswa::class);
    }

    /**
     * Relationship: TranskripCapaian generated by an Admin
     */
    public function generatedBy()
    {
        return $this->belongsTo(Admin::class, 'generated_by');
    }

    /**
     * Get validation rules for this model
     *
     * @return array<string, string|array>
     */
    public static function validationRules(): array
    {
        return [
            'siswa_id' => 'required|exists:siswas,id',
            'tanggal_generate' => 'required|date',
            'reason' => 'required|in:target_kelulusan_change,batas_tingkat_change,manual_admin,lulus_tahfidz,lulus_akademik',
            'generated_by' => 'nullable|exists:admins,id',
            'total_juz_tuntas_snapshot' => 'required|integer|min:0',
            'detail_capaian_snapshot' => 'required|array',
            'target_kelulusan_at_snapshot' => 'required|integer|min:1',
            'batas_tingkat_at_snapshot' => 'required|array',
        ];
    }

    /**
     * Scope: Get snapshots by reason
     *
     * @param \Illuminate\Database\Eloquent\Builder $query
     * @param string $reason
     * @return \Illuminate\Database\Eloquent\Builder
     */
    public function scopeByReason($query, string $reason)
    {
        return $query->where('reason', $reason);
    }

    /**
     * Scope: Get snapshots for a specific siswa
     *
     * @param \Illuminate\Database\Eloquent\Builder $query
     * @param int $siswaId
     * @return \Illuminate\Database\Eloquent\Builder
     */
    public function scopeForSiswa($query, int $siswaId)
    {
        return $query->where('siswa_id', $siswaId);
    }

    /**
     * Scope: Get automated snapshots (not manual admin)
     *
     * @param \Illuminate\Database\Eloquent\Builder $query
     * @return \Illuminate\Database\Eloquent\Builder
     */
    public function scopeAutomated($query)
    {
        return $query->whereIn('reason', ['target_kelulusan_change', 'batas_tingkat_change']);
    }

    /**
     * Scope: Get manual admin snapshots
     *
     * @param \Illuminate\Database\Eloquent\Builder $query
     * @return \Illuminate\Database\Eloquent\Builder
     */
    public function scopeManual($query)
    {
        return $query->where('reason', 'manual_admin');
    }

    /**
     * Check if this snapshot was generated automatically
     *
     * @return bool
     */
    public function isAutomated(): bool
    {
        return in_array($this->reason, ['target_kelulusan_change', 'batas_tingkat_change']);
    }

    /**
     * Check if this snapshot was generated manually by Admin
     *
     * @return bool
     */
    public function isManual(): bool
    {
        return $this->reason === 'manual_admin';
    }

    /**
     * Get formatted reason for display
     *
     * @return string
     */
    public function getFormattedReason(): string
    {
        return match($this->reason) {
            'target_kelulusan_change' => 'Perubahan Target Kelulusan',
            'batas_tingkat_change' => 'Perubahan Batas Tingkat',
            'manual_admin' => 'Snapshot Manual Admin',
            'lulus_tahfidz' => 'Lulus Program Tahfidz',
            'lulus_akademik' => 'Lulus Akademik (Tamat SMP)',
            default => $this->reason,
        };
    }

    /**
     * Scope: Get snapshots untuk kelulusan
     */
    public function scopeKelulusan($query)
    {
        return $query->whereIn('reason', ['lulus_tahfidz', 'lulus_akademik']);
    }
}
